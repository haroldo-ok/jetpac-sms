_isr_im2::
        push    af
        in      a, (0xBF)           ; VDP status (acknowledges the interrupt)
        rlca
        jr      c, 1$
        ; ---- line interrupt: sound tick
        ld      a, (_snd_ptr + 1)   ; no sequence playing?
        or      a, a
        jr      z, 2$
        ld      a, (_snd_left)
        dec     a
        ld      (_snd_left), a
        jr      nz, 2$
        push    bc
        push    de
        push    hl
        push    iy
        call    _snd_next           ; next segment of the sequence
        pop     iy
        pop     hl
        pop     de
        pop     bc
    2$:
        pop     af
        ei
        reti
    1$:
        ; ---- frame interrupt
        ld      a, #1
        ld      (_vb_flag), a
        in      a, (0xDC)
        ld      (_pad_raw), a
        in      a, (0xDD)
        ld      (_pad_raw + 1), a
        pop     af
        ei
        reti
