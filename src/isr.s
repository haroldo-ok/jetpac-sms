; Lean interrupt handler (interrupt mode 2).
; The SMS data bus is undefined during the interrupt acknowledge, so the
; 257-byte vector table holds one value everywhere: any vector byte gives
; address 0x7D7D, where the handler lives.
;   line interrupt (every 4 scanlines): beeper-emulation tick
;   frame interrupt: set the vblank flag and sample both joypads
        .module isr
        .globl  _vb_flag
        .globl  _pad_raw
        .globl  _snd_ptr
        .globl  _snd_left
        .globl  _snd_next

