#!/usr/bin/env python3
"""Generate src/gen_sfx.c: PSG renditions of the original beeper routines.

Each SFX is a list of segments (period, ticks); period = PSG tone period
(0 = silence), ticks = duration in line-interrupt ticks of 4 scanlines
(912 SMS cycles ~= 891 ZX T-states).  Segment lists end with ticks == 0.
"""
import os
ZX_T_PER_TICK = 891.0          # 4 SMS scanlines in ZX T-states (3.5MHz)
PSG_SCALE = 3579545.0 / (3500000.0 * 32.0)   # ZX period (T) -> PSG period units

def psg_period(period_T):
    n = int(round(period_T * PSG_SCALE))
    return max(1, min(1023, n))

def squarewave(D, C):
    """PlaySquareWave: C cycles of (ON D djnz loops, OFF D djnz loops)."""
    period = 2 * 13 * D + 36
    ticks = max(1, int(round(C * period / ZX_T_PER_TICK)))
    return [(psg_period(period), ticks)]

def sweep(steps):
    """steps = list of (period_T, duration_T) fine-grained; merge into >=1-tick segments."""
    segs = []
    acc_t = 0.0; acc_pt = 0.0
    for period, dur in steps:
        acc_t += dur; acc_pt += period * dur
        if acc_t >= ZX_T_PER_TICK:
            ticks = int(acc_t / ZX_T_PER_TICK)
            segs.append((psg_period(acc_pt / acc_t), ticks))
            acc_t -= ticks * ZX_T_PER_TICK
            acc_pt = period * acc_t
    if acc_t > ZX_T_PER_TICK * 0.4:
        segs.append((psg_period(acc_pt / acc_t), 1))
    return segs

def laser():
    steps = []
    for c in range(8, 0x38):
        period = 2 * 13 * c + 30          # ON c, OFF c (+ leading silence c of next step, ignored for pitch)
        steps.append((period, 3 * 13 * c + 30))
    return sweep(steps)

def chirp(c0):
    steps = []
    for c in range(c0, 0, -1):
        period = 2 * 13 * c + 30
        steps.append((period, period))
    return sweep(steps)

def explosion(player):
    """3 frames: each frame one chirp then silence until the next frame (78 ticks/frame)."""
    segs = []
    for dur in (3, 2, 1):
        c0 = 16 if player else dur + 24
        ch = chirp(c0)
        used = sum(t for _, t in ch)
        segs += ch
        segs.append((0, max(1, 78 - used)))
    return segs

def emit(name, segs):
    out = ['const unsigned char %s[] = {' % name]
    for p, t in segs:
        out.append('  %d,%d,%d,' % (p & 0xFF, p >> 8, t))
    out.append('  0,0,0 };')
    return '\n'.join(out)

parts = ['/* generated by tools/gen_sfx.py - do not edit */', '#include "game.h"']
parts.append(emit('sfx_build', squarewave(0x20, 0x50)))
parts.append(emit('sfx_pickup_fuel', squarewave(0x50, 0x28)))
parts.append(emit('sfx_pickup_item', squarewave(0x30, 0x40)))
parts.append(emit('sfx_laser', laser()))
parts.append(emit('sfx_explode_enemy', explosion(False)))
parts.append(emit('sfx_explode_player', explosion(True)))
# thrust: D = ((Y>>3)&0x1F)|0x40 -> 64..95, C=16 ; table of (period lo, period hi, ticks)
rows = []
for D in range(64, 96):
    (p, t), = squarewave(D, 0x10)
    rows.append('  %d,%d,%d,' % (p & 0xFF, p >> 8, t))
parts.append('const unsigned char sfx_thrust_tab[32*3] = {\n' + '\n'.join(rows) + '\n};')
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'gen_sfx.c'), 'w').write('\n'.join(parts) + '\n')
print('laser segs', len(laser()), 'explosion segs', len(explosion(False)), len(explosion(True)))
